/** 何ターンに 1 回、通知の広告を出すか */
export function toastEvery(level: Level): number {
  return level === 1 ? 3 : level === 2 ? 2 : 1
}

/** 「× 閉じる」を押したときの返事。before は押す前のレベル、count はこのセッションで押した回数 */
export function pressReply(before: Level, count: number): string {
  if (before === 1) return '× を押しましたね。お礼に広告を増やしておきました（広告レベル 2）'
  if (before === 2) return '閉じられませんでした。代わりに大増量です（広告レベル 3・MAX）'

  const max = [
    'これ以上は増やせません。店主も困っています',
    '本当に閉じたいときは「/chindon 店じまい」と打ってください（小声）',
    'ポン！（押すたびに、たぬき がお腹を叩きます）',
  ] as const

  return max[count % max.length] ?? max[0]
}

/** 帯の「×」のラベル */
export function closeLabel(level: Level): string {
  return level === 3 ? '× 閉じる（効きません）' : '× 閉じる'
}
